/** Несколько условий одной фразой (часть 30д «Анамнеза»): «при» — один раз, последнее — через «и». */
export function whenList(words: string[]): string {
  const rest = words.slice(1).map(w => w.replace(/^при /, ''));
  return `${[words[0], ...rest.slice(0, -1)].join(', ')} и ${rest[rest.length - 1]}`;
}
