const day = (from: number, to: number) => (from !== to ? `on days ${from}–${to}` : from === 0 ? 'the same day' : `on day ${from}`);
const days = (lo: number, hi: number) => `${lo === hi ? lo : `${lo}–${hi}`} ${plural(hi, 'day', 'days')}`;

